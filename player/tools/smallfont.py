def tile(ch):
    rows = G.get(ch, G[' ']).split()
    im = Image.new('P', (8, 8), 0); px = im.load()
    face = set()
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '1': face.add((x + 1, y + 1))
    for (x, y) in face: px[x, y] = 1
    for (x, y) in face:
        if (x + 1, y + 1) not in face and 0 <= x + 1 < 8 and 0 <= y + 1 < 8 and px[x + 1, y + 1] == 0: px[x + 1, y + 1] = 2
    return im


def tiles_bytes(encode):
    return b''.join(encode(tile(chr(c))) for c in range(32, 96))
